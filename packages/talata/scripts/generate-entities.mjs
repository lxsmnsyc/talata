// Writes src/inline/entities.ts from the WHATWG list of named character
// references. Only names that end in a semicolon are kept, as micromark does.
//
//   node scripts/generate-entities.mjs [entities.json]
//
// Without an argument it downloads https://html.spec.whatwg.org/entities.json.
import { readFileSync, writeFileSync } from 'node:fs';

const url = 'https://html.spec.whatwg.org/entities.json';
const file = process.argv[2];
const json = file ? readFileSync(file, 'utf8') : await (await fetch(url)).text();

/**
 * @param {unknown} value
 * @returns {Map<string, string>}
 */
function readList(value) {
  /** @type {Map<string, string>} */
  const result = new Map();
  if (typeof value !== 'object' || value === null) {
    throw new Error('entities.json is not an object');
  }
  for (const key of Object.keys(value).sort()) {
    /** @type {unknown} */
    const entry = Reflect.get(value, key);
    if (typeof entry !== 'object' || entry === null || !('characters' in entry)) {
      throw new Error('entry without characters: ' + key);
    }
    const characters = entry.characters;
    if (typeof characters !== 'string') {
      throw new Error('entry without characters: ' + key);
    }
    result.set(key, characters);
  }
  return result;
}

const parts = [];
for (const [key, value] of readList(JSON.parse(json))) {
  if (!key.startsWith('&') || !key.endsWith(';')) {
    continue;
  }
  const name = key.slice(1, -1);
  if (value.includes(' ') || name.includes(' ')) {
    throw new Error('the table format needs entries without spaces: ' + key);
  }
  parts.push(name, value);
}

// A single-quoted literal, as the formatter writes it.
const literal =
  "'" +
  JSON.stringify(parts.join(' ')).slice(1, -1).replaceAll('\\"', '"').replaceAll("'", "\\'") +
  "'";

const output = `// Generated by scripts/generate-entities.mjs from ${url}. Do not edit.
// Named character references that end in a semicolon, as space-separated
// name and value pairs. No value contains a space.
const table =
  ${literal};

let names: Map<string, string> | undefined;

/** The characters for a named reference (without \`&\` and \`;\`), or undefined. */
export default function decodeNamed(name: string): string | undefined {
  if (names === undefined) {
    names = new Map();
    const parts = table.split(' ');
    for (let i = 0; i < parts.length; i += 2) {
      names.set(parts[i], parts[i + 1]);
    }
  }
  return names.get(name);
}
`;

writeFileSync(new URL('../src/inline/entities.ts', import.meta.url), output);
process.stdout.write(`wrote ${parts.length / 2} entities\n`);
