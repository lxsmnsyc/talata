// Writes src/inline/entities.ts from the WHATWG list of named character
// references. Only names that end in a semicolon are kept, as micromark does.
//
//   node scripts/generate-entities.mjs [entities.json]
//
// Without an argument it downloads https://html.spec.whatwg.org/entities.json.
import { readFileSync, writeFileSync } from 'node:fs';

const url = 'https://html.spec.whatwg.org/entities.json';
const file = process.argv[2];
const json = file ? readFileSync(file, 'utf8') : await (await fetch(url)).text();

/**
 * @param {unknown} value
 * @returns {Map<string, string>}
 */
function readList(value) {
  /** @type {Map<string, string>} */
  const result = new Map();
  if (typeof value !== 'object' || value === null) {
    throw new Error('entities.json is not an object');
  }
  for (const key of Object.keys(value).sort()) {
    /** @type {unknown} */
    const entry = Reflect.get(value, key);
    if (typeof entry !== 'object' || entry === null || !('characters' in entry)) {
      throw new Error('entry without characters: ' + key);
    }
    const characters = entry.characters;
    if (typeof characters !== 'string') {
      throw new Error('entry without characters: ' + key);
    }
    result.set(key, characters);
  }
  return result;
}

// Entries in name order. Each is one base-36 digit (how many leading
// characters it shares with the previous name), the rest of the name, then the
// value. Values hold no ASCII letter or digit, so the next digit ends them.
// The one exception, `fjlig` (value "fj"), is left out and decoded by hand.
let previous = '';
let table = '';
let count = 1;
for (const [key, value] of readList(JSON.parse(json))) {
  if (!key.startsWith('&') || !key.endsWith(';')) {
    continue;
  }
  const name = key.slice(1, -1);
  if (name === 'fjlig') {
    continue;
  }
  if (/[0-9A-Za-z]/.test(value) || !/^[0-9A-Za-z]+$/.test(name)) {
    throw new Error('the table format needs plain names and values without letters: ' + key);
  }
  let shared = 0;
  while (shared < previous.length && shared < name.length && previous[shared] === name[shared]) {
    shared++;
  }
  table += shared.toString(36) + name.slice(shared) + value;
  previous = name;
  count++;
}

// A single-quoted literal, as the formatter writes it.
const literal =
  "'" + JSON.stringify(table).slice(1, -1).replaceAll('\\"', '"').replaceAll("'", "\\'") + "'";

const output = `// Generated by scripts/generate-entities.mjs from ${url}. Do not edit.
// Named character references that end in a semicolon. Each entry is one
// base-36 digit (how many leading characters it shares with the previous
// name), the rest of the name, then the value. Values hold no ASCII letter or
// digit, so the next entry's digit ends them. \`fjlig\` is added by hand.
// The \`browser\` build uses entities.browser.ts instead.
import { isAsciiAlphanumeric } from './classify';

const table =
  ${literal};

let names: Map<string, string> | undefined;

/** The characters for a named reference (without \`&\` and \`;\`), or undefined. */
export default function decodeNamed(name: string): string | undefined {
  if (names === undefined) {
    names = new Map([['fjlig', 'fj']]);
    const length = table.length;
    let current = '';
    let i = 0;
    while (i < length) {
      const start = i + 1;
      i = start;
      while (isAsciiAlphanumeric(table.charCodeAt(i))) {
        i++;
      }
      current = current.slice(0, Number.parseInt(table[start - 1], 36)) + table.slice(start, i);
      const value = i;
      while (i < length && !isAsciiAlphanumeric(table.charCodeAt(i))) {
        i++;
      }
      names.set(current, table.slice(value, i));
    }
  }
  return names.get(name);
}
`;

writeFileSync(new URL('../src/inline/entities.ts', import.meta.url), output);
process.stdout.write(`wrote ${count} entities\n`);
