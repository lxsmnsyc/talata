describe('directive extension', () => {
  const options = [false, true] as const;
  for (const gfm of options) {
    test(`reference test inputs, gfm ${gfm}`, () => {
      for (const input of referenceInputs) {
        expect(parseTalata(input, gfm, ['directive']), JSON.stringify(input)).toEqual(
          parseReference(input, gfm, ['directive']),
        );
      }
    });
    test(`own cases, gfm ${gfm}`, () => {
      for (const input of ownInputs) {
        expect(parseTalata(input, gfm, ['directive']), JSON.stringify(input)).toEqual(
          parseReference(input, gfm, ['directive']),
        );
      }
    });
    test(`frontmatter and directives, gfm ${gfm}`, () => {
      for (const input of [
        '---\n:::a\nb\n:::',
        '---\na: b\n---\n:::a\nb\n:::',
        '---\n:::a\nb\n---\n:::',
      ]) {
        expect(
          parseTalata(input, gfm, ['frontmatter', 'directive']),
          JSON.stringify(input),
        ).toEqual(parseReference(input, gfm, ['frontmatter', 'directive']));
      }
    });
  }

  test('the extension is the same object for every call', () => {
    expect(directive()).toBe(directive());
    expect(fromMarkdown(':a', { extensions: [directive()] }).children).toHaveLength(1);
  });

  test('without the extension a directive is text', () => {
    expect(fromMarkdown(':a[b]').children[0].type).toBe('paragraph');
  });
});
