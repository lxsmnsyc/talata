describe('directive extension', () => {
  const options = [false, true] as const;
  for (const gfm of options) {
    test(`reference test inputs, gfm ${gfm}`, () => {
      for (const input of referenceInputs) {
        expect(parseTalata(input, gfm, ['directive']), JSON.stringify(input)).toEqual(
          parseReference(input, gfm, ['directive']),
        );
      }
    });
    test(`own cases, gfm ${gfm}`, () => {
      for (const input of ownInputs) {
        expect(parseTalata(input, gfm, ['directive']), JSON.stringify(input)).toEqual(
          parseReference(input, gfm, ['directive']),
        );
      }
    });
    test(`containers around and inside, gfm ${gfm}`, () => {
      for (const input of containerInputs) {
        for (const names of [['directive'], ['frontmatter', 'math', 'directive']] as const) {
          expect(parseTalata(input, gfm, [...names]), JSON.stringify(input)).toEqual(
            parseReference(input, gfm, [...names]),
          );
        }
      }
    });
    test(`frontmatter and directives, gfm ${gfm}`, () => {
      for (const input of [
        '---\n:::a\nb\n:::',
        '---\na: b\n---\n:::a\nb\n:::',
        '---\n:::a\nb\n---\n:::',
      ]) {
        expect(
          parseTalata(input, gfm, ['frontmatter', 'directive']),
          JSON.stringify(input),
        ).toEqual(parseReference(input, gfm, ['frontmatter', 'directive']));
      }
    });
  }

  test('the extension is the same object for every call', () => {
    expect(directive()).toBe(directive());
    expect(fromMarkdown(':a', { extensions: [directive()] }).children).toHaveLength(1);
  });

  test('without the extension a directive is text', () => {
    expect(fromMarkdown(':a[b]').children[0].type).toBe('paragraph');
  });
});

// The benchmark corpus with the extension on, alone and with frontmatter and
// math. The suite skips when the corpus has not been downloaded.
const files = corpusFiles();
const timeout = 30_000;

describe.skipIf(files.length === 0)('benchmark corpus with directive', () => {
  for (const gfm of [false, true]) {
    for (const file of files) {
      it(
        `${file.name} ${gfm ? 'with' : 'without'} gfm`,
        () => {
          const value = readFileSync(file.path, 'utf8');
          for (const names of [['directive'], ['frontmatter', 'math', 'directive']] as const) {
            const found = firstDiff(
              parseReference(value, gfm, [...names]),
              parseTalata(value, gfm, [...names]),
            );
            expect(describeDiff(found), names.join(' ')).toBeUndefined();
          }
        },
        timeout,
      );
    }
  }
});
